#!/usr/bin/env node
/**
 * Generate icons/data/icon-data.ts and icons/data/featured-icon-data.ts
 * from the source SVG files. Inline string literals are what aegisx-ui
 * (and other Angular consumers) feed into MatIconRegistry.addSvgIconLiteral.
 *
 * Run:
 *   pnpm run gen:icon-data
 *
 * Idempotent — writes the same output for the same SVGs.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const dataDir = resolve(root, 'icons/data');
mkdirSync(dataDir, { recursive: true });

const HEADER = `// AUTO-GENERATED by scripts/generate-icon-data.mjs — DO NOT EDIT BY HAND.
// Source: icons/svg/*.svg (and featured-error/*.svg)
// Run \`pnpm run gen:icon-data\` to refresh.\n`;

function loadDir(dir) {
  return readdirSync(dir)
    .filter((f) => f.endsWith('.svg'))
    .sort()
    .map((f) => {
      const name = basename(f, '.svg');
      const svg = readFileSync(resolve(dir, f), 'utf8').replace(/\s+/g, ' ').trim();
      return { name, svg };
    });
}

function emit(records, exportName, file) {
  const lines = records
    .map(({ name, svg }) => `  ${JSON.stringify(name)}: ${JSON.stringify(svg)},`)
    .join('\n');
  const body = `${HEADER}
export const ${exportName} = {
${lines}
} as const;

export type ${exportName.replace(/_/g, '')}Name = keyof typeof ${exportName};
`;
  writeFileSync(resolve(dataDir, file), body);
  console.log(`✓ ${file} (${records.length} icons)`);
}

emit(loadDir(resolve(root, 'icons/svg')), 'AEGISX_ICON_DATA', 'icon-data.ts');
emit(loadDir(resolve(root, 'icons/featured-error')), 'AEGISX_FEATURED_ICON_DATA', 'featured-icon-data.ts');

const indexBody = `${HEADER}
export * from './icon-data.js';
export * from './featured-icon-data.js';
`;
writeFileSync(resolve(dataDir, 'index.ts'), indexBody);
console.log('✓ icons/data/index.ts');
