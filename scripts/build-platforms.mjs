#!/usr/bin/env node
/**
 * Multi-platform token export. Reads tokens/dtcg/*.json and emits
 * native bindings under dist/tokens/ for non-CSS consumers.
 *
 * Outputs:
 *   dist/tokens/tailwind/tailwind-preset.cjs    Tailwind config preset
 *   dist/tokens/ios/AegisXTokens.swift          iOS Swift static struct
 *   dist/tokens/android/colors.xml              Android XML resources
 *   dist/tokens/android/dimens.xml
 *   dist/tokens/flutter/aegisx_tokens.dart      Flutter Dart constants
 *
 * Zero deps — kept lightweight on purpose. Style Dictionary not required.
 *
 * Usage: pnpm tokens:platforms
 */
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const dtcg = resolve(root, 'tokens/dtcg');
const out  = resolve(root, 'dist/tokens');

const read = (n) => JSON.parse(readFileSync(resolve(dtcg, n), 'utf8'));
const color   = read('color.json').color;
const spacing = read('spacing.json').spacing;
const radius  = read('radius.json').radius;
const font    = read('typography.json').typography;

const ROLES = { brand: 'indigo', success: 'green', warning: 'amber', error: 'red', info: 'blue' };
const VARIANTS = { faint: 50, muted: 100, subtle: 200, default: 500, emphasis: 700 };

const hex = (hue, step) => color.palette[hue][step].$value;
const remToPx = (rem) => parseFloat(rem) * 16;

const ensure = (p) => mkdirSync(dirname(p), { recursive: true });

// ───────────────────────────────────────────────────────────────
// 1. TAILWIND PRESET
// ───────────────────────────────────────────────────────────────
const tailwindColors = (() => {
  const c = {};
  for (const hue of Object.keys(color.palette)) {
    c[hue] = {};
    for (const [step, entry] of Object.entries(color.palette[hue])) {
      c[hue][step] = entry.$value;
    }
  }
  // Add semantic aliases
  c.brand = {}; c.success = {}; c.warning = {}; c.error = {}; c.info = {};
  for (const [role, hue] of Object.entries(ROLES)) {
    for (const [variant, step] of Object.entries(VARIANTS)) {
      c[role][variant] = hex(hue, step);
    }
  }
  return c;
})();

const tailwindSpacing = Object.fromEntries(
  Object.entries(spacing).filter(([k]) => !['component','layout','inset','stack','_container_note'].includes(k))
                          .filter(([_, v]) => typeof v === 'object' && v.$value)
                          .map(([k, v]) => [k, v.$value])
);
const tailwindRadius = Object.fromEntries(
  Object.entries(radius).map(([k, v]) => [k, v.$value])
);

const tailwindPreset = `// AUTO-GENERATED by scripts/build-platforms.mjs · DO NOT EDIT
// Source: aegisx-design-system tokens/dtcg/*.json
// Use: in tailwind.config.js → presets: [require('@aegisx-platform/design-system/tokens/tailwind/tailwind-preset')]

module.exports = {
  theme: {
    extend: {
      colors: ${JSON.stringify(tailwindColors, null, 2).split('\n').join('\n      ')},
      spacing: ${JSON.stringify(tailwindSpacing, null, 2).split('\n').join('\n      ')},
      borderRadius: ${JSON.stringify(tailwindRadius, null, 2).split('\n').join('\n      ')},
      fontFamily: {
        sans: ${JSON.stringify(font.fontFamily.sans.$value.split(',').map((s) => s.trim().replace(/^"|"$/g, '')))},
        mono: ${JSON.stringify(font.fontFamily.mono.$value.split(',').map((s) => s.trim().replace(/^"|"$/g, '')))},
      },
    },
  },
};
`;
ensure(`${out}/tailwind/tailwind-preset.cjs`);
writeFileSync(`${out}/tailwind/tailwind-preset.cjs`, tailwindPreset);

// ───────────────────────────────────────────────────────────────
// 2. iOS SWIFT
// ───────────────────────────────────────────────────────────────
const swiftColor = (h) => {
  const r = parseInt(h.slice(1, 3), 16) / 255;
  const g = parseInt(h.slice(3, 5), 16) / 255;
  const b = parseInt(h.slice(5, 7), 16) / 255;
  return `Color(red: ${r.toFixed(3)}, green: ${g.toFixed(3)}, blue: ${b.toFixed(3)})`;
};

let swift = `// AUTO-GENERATED by scripts/build-platforms.mjs · DO NOT EDIT
// AegisX design tokens for SwiftUI / iOS.
import SwiftUI

public enum AegisXColor {
`;
for (const hue of Object.keys(color.palette)) {
  for (const [step, entry] of Object.entries(color.palette[hue])) {
    const camel = `${hue}${step}`;
    swift += `  public static let ${camel} = ${swiftColor(entry.$value)}\n`;
  }
}
swift += `\n  // Semantic roles\n`;
for (const [role, hue] of Object.entries(ROLES)) {
  for (const [variant, step] of Object.entries(VARIANTS)) {
    swift += `  public static let ${role}${variant.charAt(0).toUpperCase()}${variant.slice(1)} = ${hue}${step}\n`;
  }
}
swift += `}

public enum AegisXSpacing {
`;
for (const [k, v] of Object.entries(spacing)) {
  if (typeof v !== 'object' || !v.$value) continue;
  swift += `  public static let ${k.replace(/^(\d)/, '_$1').replace('-', '_')}: CGFloat = ${remToPx(v.$value)}\n`;
}
swift += `}

public enum AegisXRadius {
`;
for (const [k, v] of Object.entries(radius)) {
  const px = v.$value === '9999px' ? 9999 : remToPx(v.$value);
  swift += `  public static let ${k.replace(/^(\d)/, '_$1')}: CGFloat = ${px}\n`;
}
swift += `}
`;
ensure(`${out}/ios/AegisXTokens.swift`);
writeFileSync(`${out}/ios/AegisXTokens.swift`, swift);

// ───────────────────────────────────────────────────────────────
// 3. ANDROID XML
// ───────────────────────────────────────────────────────────────
const androidName = (s) => s.replace(/-/g, '_').replace(/^(\d)/, 'n$1');

let colorsXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- AUTO-GENERATED by scripts/build-platforms.mjs · DO NOT EDIT -->
<resources>
`;
for (const hue of Object.keys(color.palette)) {
  for (const [step, entry] of Object.entries(color.palette[hue])) {
    colorsXml += `    <color name="ax_${hue}_${step}">${entry.$value}</color>\n`;
  }
}
colorsXml += `\n    <!-- Semantic roles -->\n`;
for (const [role, hue] of Object.entries(ROLES)) {
  for (const [variant, step] of Object.entries(VARIANTS)) {
    colorsXml += `    <color name="ax_${role}_${variant}">${hex(hue, step)}</color>\n`;
  }
}
colorsXml += `</resources>
`;
ensure(`${out}/android/colors.xml`);
writeFileSync(`${out}/android/colors.xml`, colorsXml);

let dimensXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- AUTO-GENERATED by scripts/build-platforms.mjs · DO NOT EDIT -->
<resources>
`;
for (const [k, v] of Object.entries(spacing)) {
  if (typeof v !== 'object' || !v.$value) continue;
  dimensXml += `    <dimen name="ax_spacing_${androidName(k)}">${remToPx(v.$value)}dp</dimen>\n`;
}
for (const [k, v] of Object.entries(radius)) {
  const px = v.$value === '9999px' ? 9999 : remToPx(v.$value);
  dimensXml += `    <dimen name="ax_radius_${androidName(k)}">${px}dp</dimen>\n`;
}
dimensXml += `</resources>
`;
ensure(`${out}/android/dimens.xml`);
writeFileSync(`${out}/android/dimens.xml`, dimensXml);

// ───────────────────────────────────────────────────────────────
// 4. FLUTTER DART
// ───────────────────────────────────────────────────────────────
const dartColor = (h) => `Color(0xFF${h.slice(1).toUpperCase()})`;

let dart = `// AUTO-GENERATED by scripts/build-platforms.mjs · DO NOT EDIT
// AegisX design tokens for Flutter / Dart.
import 'package:flutter/painting.dart';

class AegisXColor {
`;
for (const hue of Object.keys(color.palette)) {
  for (const [step, entry] of Object.entries(color.palette[hue])) {
    dart += `  static const ${hue}${step} = ${dartColor(entry.$value)};\n`;
  }
}
dart += `\n  // Semantic roles\n`;
for (const [role, hue] of Object.entries(ROLES)) {
  for (const [variant, step] of Object.entries(VARIANTS)) {
    dart += `  static const ${role}${variant.charAt(0).toUpperCase()}${variant.slice(1)} = ${dartColor(hex(hue, step))};\n`;
  }
}
dart += `}

class AegisXSpacing {
`;
for (const [k, v] of Object.entries(spacing)) {
  if (typeof v !== 'object' || !v.$value) continue;
  const name = k.replace(/^(\d)/, 's$1').replace('-', '_');
  dart += `  static const ${name} = ${remToPx(v.$value)}.0;\n`;
}
dart += `}

class AegisXRadius {
`;
for (const [k, v] of Object.entries(radius)) {
  const px = v.$value === '9999px' ? 9999 : remToPx(v.$value);
  const name = k.replace(/^(\d)/, 'r$1');
  dart += `  static const ${name} = ${px}.0;\n`;
}
dart += `}
`;
ensure(`${out}/flutter/aegisx_tokens.dart`);
writeFileSync(`${out}/flutter/aegisx_tokens.dart`, dart);

console.log(`✓ Wrote dist/tokens/{tailwind,ios,android,flutter} from DTCG`);
